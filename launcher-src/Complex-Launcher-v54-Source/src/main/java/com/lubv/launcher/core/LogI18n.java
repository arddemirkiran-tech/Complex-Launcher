    private static final List<String[]> SORTED = new ArrayList<>();
    static {
        for (String[] p : T) SORTED.add(p);
        SORTED.sort((a, b) -> Integer.compare(b[0].length(), a[0].length()));
    }

    /** Dil Ingilizce ise bilinen Turkce parcalari cevirir; degilse metni aynen dondurur. */
    public static String tr(String s) {
        if (s == null || s.isEmpty() || !L10n.isEnglish()) return s;
        String out = s;
        for (String[] p : SORTED) {
            if (out.contains(p[0])) out = out.replace(p[0], p[1]);
        }
        return out;
    }
